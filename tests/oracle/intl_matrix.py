_SWEEP_OPTIONS: list[dict[str, str]] = [
    {},
    {"dateStyle": "full", "timeStyle": "long"},
    {"weekday": "long", "year": "numeric", "month": "long", "day": "numeric"},
    {"hour": "numeric", "minute": "2-digit"},
]


def cases() -> list[Case]:
    """Every case, in a fixed order."""
    found: list[Case] = []
    rotation = itertools.cycle(itertools.product(MOMENTS, ZONES))
    for locale, options in itertools.product(LOCALES, OPTION_SETS):
        for _ in range(2):
            moment, zone = next(rotation)
            found.append(("format", moment, zone, {"locale": locale, **options}))
    for locale, options, zone, moment in itertools.product(
        _ZONE_LOCALES, ZONE_OPTION_SETS, ZONES, MOMENTS[:6]
    ):
        found.append(("format", moment, zone, {"locale": locale, **options}))
    for locale, options in itertools.product(LOCALES[::7], OPTION_SETS[::5]):
        moment, zone = next(rotation)
        # formatUtc puts UTC over a timeZone option; formatLocal takes it.
        found.append(("formatUtc", moment, "UTC", {"locale": locale, "timeZone": zone, **options}))
        found.append(
            ("formatLocal", moment, "UTC", {"locale": locale, "timeZone": zone, **options})
        )
    for index, (locale, options) in enumerate(itertools.product(NODE_LOCALES, _SWEEP_OPTIONS)):
        moment, zone = MOMENTS[index % 7], ZONES[index % len(ZONES)]
        found.append(("format", moment, zone, {"locale": locale, **options}))
    for locale, options in itertools.product(
        EXTENSION_LOCALES + EDGE_LOCALES + UNSUPPORTED_CALENDAR_LOCALES, OPTION_SETS[::3]
    ):
        moment, zone = next(rotation)
        found.append(("format", moment, zone, {"locale": locale, **options}))
    for options in OPTION_SETS:
        moment, zone = next(rotation)
        found.append(("format", moment, zone, options))
        found.append(("formatUtc", moment, "UTC", options))
    old_locales = [
        "en-US",
        "en-GB",
        "fr-FR",
        "th-TH",
        "fa-IR",
        "ar-EG",
        "ja-JP",
        "en-US-u-ca-buddhist",
    ]
    old_zones = ["UTC", "America/New_York", "Asia/Kolkata", "+05:30"]
    for locale, moment, zone, options in itertools.product(
        old_locales, OLD_MOMENTS, old_zones, OPTION_SETS[::4]
    ):
        found.append(("format", moment, zone, {"locale": locale, **options}))
    return found
