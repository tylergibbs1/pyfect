@pytest.mark.parametrize(
    ("zone_id", "instant", "hours"),
    [
        ("SystemV/AST4ADT", datetime(2024, 7, 1, tzinfo=UTC), -3),
        ("SystemV/AST4ADT", datetime(2024, 1, 15, tzinfo=UTC), -4),
        ("SystemV/AST4ADT", datetime(1850, 7, 1, tzinfo=UTC), -4),
        ("SystemV/PST8PDT", datetime(1950, 4, 30, 12, tzinfo=UTC), -7),
        ("SystemV/PST8PDT", datetime(1950, 4, 29, 12, tzinfo=UTC), -8),
        ("SystemV/HST10", datetime(2024, 7, 1, tzinfo=UTC), -10),
        ("-0830", datetime(1850, 7, 1, tzinfo=UTC), -8.5),
    ],
)
def test_zones_tz_dropped_keep_icus_rules(zone_id: str, instant: datetime, hours: float) -> None:
    # Node 24.22.1: the longOffset Intl gives for zone_id at instant
    zone = date_time.zone_named(zone_id)
    assert zone is not None
    offset = instant.astimezone(zone).utcoffset()
    assert offset is not None
    assert offset.total_seconds() == hours * 3600


def test_zones_pickle_as_their_id() -> None:
    for zone_id in ("Asia/Calcutta", "SystemV/AST4ADT", "+05:30"):
        zone = date_time.zone_named(zone_id)
        assert pickle.loads(pickle.dumps(zone)) is zone


def test_a_canonical_id_zoneinfo_lacks_reads_another_ids_file(tmp_path: Path) -> None:
    """Debian's tzdata leaves old link names (``Asia/Calcutta``) to
    tzdata-legacy: the zone still loads, under ICU's id."""
    (tmp_path / "Asia").mkdir()
    kolkata = next(Path(d, "Asia/Kolkata") for d in TZPATH if Path(d, "Asia/Kolkata").exists())
    shutil.copyfile(kolkata, tmp_path / "Asia" / "Kolkata")
    script = (
        "import pickle; from datetime import datetime, UTC; from pyfect import date_time\n"
        "z = date_time.zone_named('Asia/Kolkata')\n"
        "print(date_time.zone_to_string(z), datetime(2024, 1, 1, tzinfo=UTC).astimezone(z)"
        ".utcoffset(), pickle.loads(pickle.dumps(z)) is z)"
    )
    env = {"PYTHONTZPATH": str(tmp_path), "PATH": ""}
    result = subprocess.run(
        [sys.executable, "-c", script], env=env, capture_output=True, text=True, check=True
    )
    assert result.stdout.split() == ["Asia/Calcutta", "5:30:00", "True"]


