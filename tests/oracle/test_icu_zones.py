def _node_version() -> str | None:
    node = shutil.which("node")
    if node is None:
        return None
    return subprocess.run(
        [node, "-p", "process.versions.node"], capture_output=True, text=True, check=True
    ).stdout.strip()


_NODE_CHECK = """
const { ids, systemv, instants } = JSON.parse(require("fs").readFileSync(0, "utf8"))
const canonical = (id) => {
  try { return new Intl.DateTimeFormat("en-US", { timeZone: id }).resolvedOptions().timeZone }
  catch { return null }
}
const offset = (zone, ms) => {
  const part = new Intl.DateTimeFormat("en-US", { timeZone: zone, timeZoneName: "longOffset" })
    .formatToParts(ms).find((p) => p.type === "timeZoneName").value
  const m = /GMT(?:([+-])(\\d\\d):(\\d\\d))?/.exec(part)
  return m[1] ? (m[1] === "-" ? -1 : 1) * (m[2] * 3600 + m[3] * 60) : 0
}
process.stdout.write(JSON.stringify({
  canonical: Object.fromEntries(ids.map((id) => [id, canonical(id)])),
  offsets: Object.fromEntries(systemv.map((z) => [z, instants.map((ms) => offset(z, ms))])),
}))
"""


def test_table_is_what_the_recorded_node_gives() -> None:
    version = _node_version()
    if version != NODE_VERSION:
        pytest.skip(f"needs Node {NODE_VERSION} (found {version})")
    offsets = ["+05:30", "+0530", "+05", "-00:00", "\u221205:00", "+23:59", "+24:00", "+5"]
    ids = [*CANONICAL, *(zone_id.upper() for zone_id in CANONICAL), "Factory", *offsets]
    instants = [
        datetime(year, month, 15, hour, tzinfo=UTC)
        for year in (1850, 1902, 1950, 1976, 1977, 2024, 2060)
        for month in (1, 4, 7, 10)
        for hour in (0, 12)
    ]
    request = {
        "ids": ids,
        "systemv": [*sorted(TZIF), "-08:30", "+05:45"],
        "instants": [int(instant.timestamp() * 1000) for instant in instants],
    }
    found = json.loads(
        subprocess.run(
            ["node", "-e", _NODE_CHECK],
            input=json.dumps(request),
            capture_output=True,
            text=True,
            check=True,
        ).stdout
    )
    for zone_id, canonical in found["canonical"].items():
        zone = date_time.zone_named(zone_id)
        assert (zone and date_time.zone_to_string(zone)) == canonical, zone_id
    for zone_id, offsets in found["offsets"].items():
        zone = date_time.zone_named(zone_id)
        assert zone is not None
        mine = [instant.astimezone(zone).utcoffset() for instant in instants]
        assert [o.total_seconds() if o else None for o in mine] == offsets, zone_id
