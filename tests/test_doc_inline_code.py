"""The guides' self-contained inline code type-checks.

Python blocks in the guides are checked snippets (`test_doc_snippets.py`), but an inline
span such as `fx.sleep("10 millis").track_duration(...)` is prose. One went stale in 0.5.0
and failed at run time. Every inline span that is a pyfect call using only module names
and literals is copied into `tests/_doc_inline_code.py`, which the pyright run checks.
Spans with placeholders (`f`, `eff`, `...`) are skipped: they aren't runnable code.

Regenerate the file with

    UPDATE_DOC_INLINE_CODE=1 uv run pytest tests/test_doc_inline_code.py
"""

import ast
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).parent.parent
GUIDES = ROOT / "website" / "content" / "docs"
CHECKED = Path(__file__).parent / "_doc_inline_code.py"

MODULES = {
    "fx": "import pyfect as fx",
    "S": "from pyfect import schema as S",
    "clock": "from pyfect import clock",
    "duration": "from pyfect import duration",
    "layer": "from pyfect import layer",
    "metric": "from pyfect import metric",
    "schedule": "from pyfect import schedule",
    "stream": "from pyfect import stream",
    "testing": "from pyfect import testing",
}

FENCE = re.compile(r"```.*?```", re.DOTALL)
SPAN = re.compile(r"`([^`\n]+)`")


def self_contained(text: str) -> ast.expr | None:
    """The span's expression if it is a call using only module names and literals."""
    try:
        expr = ast.parse(text, mode="eval").body
    except SyntaxError:
        return None
    nodes = list(ast.walk(expr))
    if not any(isinstance(n, ast.Call) for n in nodes):
        return None
    if any(isinstance(n, ast.Constant) and n.value is Ellipsis for n in nodes):
        return None
    bound = {a.arg for n in nodes if isinstance(n, ast.Lambda) for a in n.args.args}
    module_uses = {
        id(n.value) for n in nodes if isinstance(n, ast.Attribute) and isinstance(n.value, ast.Name)
    }
    names = [n for n in nodes if isinstance(n, ast.Name) and n.id not in bound]
    if not names:
        return None
    # A module name used bare (`fx.provide(layer)`) is a placeholder, not the module.
    if any(n.id not in MODULES or id(n) not in module_uses for n in names):
        return None
    return expr


def inline_expressions(text: str) -> list[str]:
    found: list[str] = []
    for match in SPAN.finditer(FENCE.sub("", text)):
        span = match.group(1)
        if self_contained(span) is not None and span not in found:
            found.append(span)
    return found


def guide_expressions() -> list[tuple[str, str]]:
    seen: set[str] = set()
    found: list[tuple[str, str]] = []
    for guide in sorted(GUIDES.rglob("*.mdx")):
        if "reference" in guide.relative_to(GUIDES).parts:
            continue
        for span in inline_expressions(guide.read_text()):
            if span not in seen:
                seen.add(span)
                found.append((guide.name, span))
    return found


def render(expressions: list[tuple[str, str]]) -> str:
    used = {
        n.id
        for _, span in expressions
        for n in ast.walk(ast.parse(span, mode="eval"))
        if isinstance(n, ast.Name) and n.id in MODULES
    }
    lines = [
        '"""Generated by tests/test_doc_inline_code.py: the guides\' inline code, type-checked."""',
        "",
        "# pyright: reportUnusedExpression=false",
        "",
        *sorted(MODULES[name] for name in used),
        "",
    ]
    for guide, span in expressions:
        lines += [f"# {guide}", span]
    return "\n".join(lines) + "\n"


def checked_expressions() -> list[str]:
    tree = ast.parse(CHECKED.read_text())
    return [
        ast.dump(s.value)
        for s in tree.body
        if isinstance(s, ast.Expr) and not isinstance(s.value, ast.Constant)
    ]


def test_the_checked_file_holds_every_self_contained_inline_span() -> None:
    expressions = guide_expressions()
    if os.environ.get("UPDATE_DOC_INLINE_CODE"):
        CHECKED.write_text(render(expressions))
        ruff = [sys.executable, "-m", "ruff"]
        subprocess.run([*ruff, "check", "-q", "--fix", "--select", "I", str(CHECKED)], check=True)
        subprocess.run([*ruff, "format", "-q", str(CHECKED)], check=True)
    wanted = [ast.dump(ast.parse(span, mode="eval").body) for _, span in expressions]
    assert checked_expressions() == wanted, "regenerate with UPDATE_DOC_INLINE_CODE=1"


def test_spans_with_placeholders_are_skipped() -> None:
    text = (
        '`fx.sleep("10 millis").track_duration(metric.histogram("h", boundaries=[1.0]))` '
        "`fx.provide(layer)` `layer.succeed(Tag, service)` `S.Literals(...)` `fx.Effect` "
        '`fx.succeed(1).pipe(fx.map(lambda x: x + 1))` `"5 seconds"`'
    )
    assert inline_expressions(text) == [
        'fx.sleep("10 millis").track_duration(metric.histogram("h", boundaries=[1.0]))',
        "fx.succeed(1).pipe(fx.map(lambda x: x + 1))",
    ]
