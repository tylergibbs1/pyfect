"""Network addresses (Effect's ``NetAddress``).

IP addresses are the standard library's ``ipaddress.IPv4Address`` and
``IPv6Address``, parsed strictly (four decimal octets without leading
zeros; IPv6 without brackets or zones) and written canonically by
``format_ip``. ``MacAddress``, ``InetAddressV4`` / ``InetAddressV6`` (an
address and port, the latter with a scope ID) and ``UnixPathAddress`` are
frozen dataclasses whose ``str`` is their canonical text::

    from pyfect.net import net_address as na

    address = na.inet_address_from_string("[fe80::1%2]:80").get_or_raise()
    na.format_inet(address)                       # "[fe80::1%2]:80"
    na.ip_from_string("01.2.3.4")                 # Err(NetAddressError(...))

Checked parsers return ``Ok`` / ``Err(NetAddressError)``; the ``_unsafe``
ones raise the error. Classifications (``is_loopback``, ``is_multicast``,
...) are Effect's bit tests and return ``bool``.
"""

