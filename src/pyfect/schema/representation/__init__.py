"""Schema representations (Effect's ``SchemaRepresentation``): a schema's
encoded side as plain, comparable, persistable data.

``to_representation(schema)`` lowers a schema to a ``Document`` (one
``Representation`` and the named ``references`` it uses); ``to_json`` /
``from_json`` persist it in Effect's JSON form; ``from_representation``
rebuilds a schema from it, given the revivers of the declarations and
checks it holds (``BUILTIN_REVIVERS`` for pyfect's own);
``to_json_schema_document`` compiles it to JSON Schema.

    from pyfect.schema import representation as R

    stored = R.to_json(R.to_representation(Person))
    schema = R.from_representation(R.from_json(stored), revivers=R.BUILTIN_REVIVERS)
"""

