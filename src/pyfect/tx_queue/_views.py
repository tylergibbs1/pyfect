"""Write-only and read-only views of a ``TxQueue``, for variance.

A ``TxQueue[A, E]`` is invariant. Code that only offers can take a
``TxEnqueue[A, E]`` (contravariant); code that only takes can take a
``TxDequeue[A, E]`` (covariant), which gives batches as ``Sequence`` and
has ``clear`` (Effect puts it on ``TxEnqueue``, but it gives back items).
"""

from __future__ import annotations

from collections.abc import Iterable, Sequence
from typing import Any, Never, Protocol, overload

from pyfect._core import Effect
from pyfect.cause import Cause
from pyfect.errors import Done
from pyfect.option import Option


class TxQueueState(Protocol):
    """What every view can ask about the queue."""

    def size(self) -> Effect[int]: ...
    def is_empty(self) -> Effect[bool]: ...
    def is_non_empty(self) -> Effect[bool]: ...
    def is_full(self) -> Effect[bool]: ...
    def is_open(self) -> Effect[bool]: ...
    def is_closing(self) -> Effect[bool]: ...
    def is_done(self) -> Effect[bool]: ...
    def is_shutdown(self) -> Effect[bool]: ...
    def await_completion(self) -> Effect[None]: ...
    @property
    def capacity(self) -> int | None: ...


class TxEnqueue[A, E](TxQueueState, Protocol):
    """The producing side of a transactional queue."""

    def offer(self, item: A) -> Effect[bool]: ...
    def offer_all[T](self: TxEnqueue[T, Any], items: Iterable[T]) -> Effect[list[T]]: ...
    def fail(self, error: E) -> Effect[bool]: ...
    def fail_cause(self, cause: Cause[E]) -> Effect[bool]: ...
    def end(self: TxEnqueue[Any, Done]) -> Effect[bool]: ...
    def interrupt(self) -> Effect[bool]: ...
    def shutdown(self) -> Effect[bool]: ...


class TxDequeue[A, E](TxQueueState, Protocol):
    """The consuming side of a transactional queue."""

    def take(self) -> Effect[A, E]: ...
    def poll(self) -> Effect[Option[A]]: ...
    def peek(self) -> Effect[A, E]: ...
    def take_all(self) -> Effect[Sequence[A], E]: ...
    def take_n(self, n: int) -> Effect[Sequence[A], E]: ...
    def take_between(self, minimum: int, maximum: int) -> Effect[Sequence[A], E]: ...
    @overload
    def clear[AA](self: TxDequeue[AA, Done[Any]]) -> Effect[Sequence[AA], Never]: ...
    @overload
    def clear[AA, EE](self: TxDequeue[AA, EE | Done[Any]]) -> Effect[Sequence[AA], EE]: ...
