"""Read-only and write-only views of a ``Queue``, for variance.

A ``Queue[A, E]`` both takes and gives ``A``s, so it is invariant. A function
that only offers can ask for an ``Enqueue[A, E]``, which is contravariant: a
``Queue[int]`` is an ``Enqueue[bool]``. A function that only takes can ask
for a ``Dequeue[A, E]``, which is covariant: a ``Queue[int, Done]`` is a
``Dequeue[float, Exception]``. Effect's ``asEnqueue`` / ``asDequeue`` are an
annotation; ``isinstance(x, Queue)`` is its ``isQueue``.

A ``Dequeue`` gives batches as ``Sequence`` (``Queue`` gives ``list``), and
its ``clear`` / ``collect`` / ``await_done`` keep ``Done`` in the error type:
only the invariant ``Queue`` can take ``Done`` out of ``E``.
"""

from __future__ import annotations

from collections.abc import Iterable, Sequence
from typing import Any, Never, Protocol

from pyfect._core import Effect
from pyfect.cause import Cause
from pyfect.errors import Done
from pyfect.option import Option


class Enqueue[A, E](Protocol):
    """The producing side of a queue."""

    def offer(self, item: A) -> Effect[bool]: ...
    def offer_all[T](self: Enqueue[T, Any], items: Iterable[T]) -> Effect[list[T]]: ...
    def fail(self, error: E) -> Effect[bool]: ...
    def fail_cause(self, cause: Cause[E]) -> Effect[bool]: ...
    def end(self: Enqueue[Any, Done]) -> Effect[bool]: ...
    def interrupt(self) -> Effect[bool]: ...
    def shutdown(self) -> Effect[bool]: ...
    def flush(self) -> Effect[None]: ...
    def into[R](self: Enqueue[Any, Done], eff: Effect[object, E, R]) -> Effect[bool, Never, R]: ...


class Dequeue[A, E](Protocol):
    """The consuming side of a queue."""

    def take(self) -> Effect[A, E]: ...
    def take_all(self) -> Effect[tuple[A, *tuple[A, ...]], E]: ...
    def take_n(self, n: int) -> Effect[Sequence[A], E]: ...
    def take_between(self, minimum: int, maximum: int) -> Effect[Sequence[A], E]: ...
    def poll(self) -> Effect[Option[A]]: ...
    def peek(self) -> Effect[A, E]: ...
    def clear(self) -> Effect[Sequence[A], E]: ...
    def collect(self) -> Effect[Sequence[A], E]: ...
    def await_done(self) -> Effect[None, E]: ...
    def size(self) -> Effect[int]: ...
    def is_full(self) -> Effect[bool]: ...
    @property
    def capacity(self) -> int | None: ...
