from pyfect.cause import die as die_cause
from pyfect.context import Context

if TYPE_CHECKING:
    from pyfect.tracer import SpanOptions

type Gen[A, E = Never, R = Never] = Generator[Effect[Any, E, R], Any, A]
"""What a generator body yields and returns: ``Gen[A, E, R]`` is the return
annotation of a body making an ``Effect[A, E, R]``. A generic body needs it
(pyright loses the type parameter otherwise; research/typing/fn_1_generic.py)."""

type Pipe[X, Y, **P] = Callable[[X], Y] | Callable[Concatenate[X, P], Y]
"""A pipeable: the previous result, then (optionally) the call's arguments."""

type _Body = Callable[..., Generator[Effect[Any, Any, Any], Any, Any]]
type _AnyBody = Callable[..., Generator[Effect[Any, Any, Any], Any, Any] | Effect[Any, Any, Any]]
type _Applied = Callable[[object, tuple[Any, ...], dict[str, Any]], object]


def _annotates_return(f: Callable[..., Any]) -> bool:
    if sys.version_info >= (3, 14):
        import annotationlib

        return "return" in annotationlib.get_annotations(f, format=annotationlib.Format.FORWARDREF)
    return "return" in inspect.get_annotations(f)


def typed_generic_body(f: Callable[..., Any], api: str) -> None:
    """``f``, checked to annotate its return type when it is generic: given a
    generic body yielding effects that need different services, pyright drops
    or collapses the type parameter (research/typing/fn_1_generic.py)."""
    if inspect.isfunction(f) and f.__type_params__ and not _annotates_return(f):
        params = ", ".join(p.__name__ for p in f.__type_params__)
        raise TypeError(
            f"{api}: {f.__qualname__} is generic ([{params}]) with no return annotation; "
            "pyright cannot infer a generic body's effect type, so annotate it: "
            "`-> fx.Gen[A, E, R]` for a generator, `-> fx.Effect[A, E, R]` for an effect"
        )


def _takes_arguments(pipeable: Callable[..., Any]) -> bool:
    """Whether ``pipeable`` takes the call's arguments after the result: a
    parameter after the first without a default, or ``*args`` / ``**kwargs``.
    A callable whose signature can't be read gets the result only."""
    try:
        parameters = list(inspect.signature(pipeable).parameters.values())[1:]
    except (TypeError, ValueError):
        return False
    variadic = (inspect.Parameter.VAR_POSITIONAL, inspect.Parameter.VAR_KEYWORD)
    return any(p.kind in variadic or p.default is inspect.Parameter.empty for p in parameters)


def _applier(pipeable: Callable[..., Any]) -> _Applied:
    if _takes_arguments(pipeable):
        return lambda value, args, kwargs: pipeable(value, *args, **kwargs)
    return lambda value, _args, _kwargs: pipeable(value)


def _appliers(pipeables: tuple[Callable[..., Any], ...]) -> tuple[_Applied, ...]:
    for i, pipeable in enumerate(pipeables):
        if not callable(pipeable):
            raise TypeError(f"fn: pipeable {i + 1} is {pipeable!r}, not a function")
    return tuple(_applier(p) for p in pipeables)


def _untraced(f: _Body, pipeables: tuple[Callable[..., Any], ...]) -> Callable[..., Any]:
    typed_generic_body(f, "fn")
    appliers = _appliers(pipeables)

    @functools.wraps(f)
    def wrapper(*args: Any, **kwargs: Any) -> Any:
        result: object = _Gen(lambda: f(*args, **kwargs))
        for apply in appliers:
            result = apply(result, args, kwargs)
        return result

    return wrapper


def _run_body(f: _AnyBody, name: str, result: object) -> Effect[Any, Any, Any]:
    # Effect.fn's ``isEffect(iter) ? iter : fromIteratorUnsafe(iter)``.
    if isinstance(result, Effect):
        return cast("Effect[Any, Any, Any]", result)
    if isinstance(result, Generator):
        generator = cast("Generator[Effect[Any, Any, Any], Any, Any]", result)
        return _Gen(lambda: generator)
    return _FailCause(
        die_cause(
            TypeError(
                f"fn({name!r}): {f.__qualname__} returned {type(result).__name__}, "
                "not an effect or a generator; an effect inside it runs only with "
                "`yield from effect`"
            )
        )
    )


def _traced(
    f: _AnyBody,
    name: str,
    definition: Callable[[], str | None],
    span: SpanOptions | None,
    pipeables: tuple[Callable[..., Any], ...],
) -> Callable[..., Any]:
    """``f`` as a function returning an effect that runs inside a span
    ``name``, unless ``span`` is ``None``, and a stack frame for the call
    (``name`` at the call site) under one for the definition."""
    from pyfect.tracer._spans import in_parent_span, span_using

    typed_generic_body(f, "fn")
    definition_name = f"{name} (definition)"
    appliers = _appliers(pipeables)

    # Built apart from ``wrapper`` so the frame never holds the call's
    # arguments, which forked fibers inheriting it would keep alive.
    def enter_at(stack: Callable[[], str | None]) -> Callable[[Context], Context]:
        def enter(ctx: Context) -> Context:
            caller = ctx.lookup(CurrentStackFrame)[1]
            frame = StackFrame(name, stack, StackFrame(definition_name, definition, caller))
            return ctx.add(CurrentStackFrame, frame)

        return enter

    @functools.wraps(f)
    def wrapper(*args: Any, **kwargs: Any) -> Any:
        result: object = _Suspend(lambda: _run_body(f, name, f(*args, **kwargs)))
        for apply in appliers:
            result = apply(result, args, kwargs)
        if not isinstance(result, Effect):
            return result
        body = cast("Effect[Any, Any, Any]", result)
        traced: Effect[Any, Any, Any] = (
            body if span is None else span_using(name, partial(in_parent_span, body), span)
        )
        located: Effect[Any, Any, Any] = _Locally(traced, enter_at(call_site(1)))
        return located

    return wrapper


