"""``fn`` and ``fn_untraced``: functions returning effects, built from a
generator body (Effect's ``Effect.fn`` / ``Effect.fnUntraced``).

Pipeables after the body post-process each call's effect, as Effect's
do: each gets the previous result, and also the call's arguments when it
takes them (a parameter after the first without a default, ``*args`` or
``**kwargs``), so ``lambda eff: ...``, ``lambda eff, user_id: ...`` and
curried combinators such as ``catch_tag(...)`` all fit. A named function's
span and stack frames wrap what the last pipeable gives, when it is an
effect; anything else comes back as it is.

The overloads, one per number of pipeables, are generated by
``tests/test_fn_overloads.py``.
"""

