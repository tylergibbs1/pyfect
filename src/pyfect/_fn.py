def fn(
    f: _Body | str,
    /,
    *pipeables: Callable[..., Any],
    **options: Unpack[SpanOptions],
) -> Callable[..., Any] | _Traced:
    """Turn a generator function with parameters into a function that
    returns an effect::

        @fn
        def find_user(user_id: str):
            db = yield from Database()
            ...

    ``@fn("name")`` (with span options as keywords) also runs every call
    inside a span of that name, the parent of the spans made inside, and
    its body may return an effect instead of yielding.

    Each call of a named function also runs inside a stack frame for its
    call site under one for the definition (``"name (definition)"``), so a
    failure inside records both (``tracer.StackTrace``). The bare ``@fn``
    is Effect's ``fnUntraced`` (``fn_untraced``): no span and no frames.

    Pipeables after the body post-process each call's effect (see the
    module docstring): ``fn(body, lambda eff, user_id: eff.map(...))``,
    ``fn("name")(body, catch_tag(NotFound, ...))``.
    """
    if isinstance(f, str):
        if pipeables:
            raise TypeError("fn(name): pass the body and pipeables to the function it returns")
        return _Traced(f, options, call_site(1))
    if options:
        raise TypeError("fn: span options go with a name, as fn(name, **span_options)(body)")
    return _untraced(f, pipeables)


