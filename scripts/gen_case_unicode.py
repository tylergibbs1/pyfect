"""Generate ``src/pyfect/_case_unicode.py``, the Unicode letter, mark and number classes the
case helpers (``pyfect.case``) split words with, as JavaScript's ``\\p{L}``, ``\\p{Lu}``,
``\\p{Ll}``, ``\\p{M}`` and ``\\p{N}`` in Effect's ``String`` module. Python's ``re`` has no Unicode
property classes, so the ranges are written out, from the same Unicode version as the URL
tables (``scripts/gen_url_unicode.py``), whatever the running Python's ``unicodedata`` has.

    uv run python scripts/gen_case_unicode.py [--source DIR] [--check]

``--source`` reads ``DerivedGeneralCategory.txt`` from ``DIR`` instead of unicode.org;
``--check`` fails when the module on disk differs from what would be written.
"""

from __future__ import annotations

import argparse
import sys
import urllib.request
from pathlib import Path

VERSION = "17.0.0"
OUT = Path(__file__).resolve().parent.parent / "src" / "pyfect" / "_case_unicode.py"
URL = f"https://www.unicode.org/Public/{VERSION}/ucd/extracted/DerivedGeneralCategory.txt"
CLASSES = {
    "LETTER": ("Lu", "Ll", "Lt", "Lm", "Lo"),
    "UPPER": ("Lu",),
    "LOWER": ("Ll",),
    "MARK": ("Mn", "Mc", "Me"),
    "NUMBER": ("Nd", "Nl", "No"),
}


def _read(source: Path | None) -> str:
    if source is not None:
        return (source / "DerivedGeneralCategory.txt").read_text()
    with urllib.request.urlopen(URL) as response:
        return response.read().decode()


def _ranges(text: str, categories: tuple[str, ...]) -> list[tuple[int, int]]:
    rows: list[tuple[int, int]] = []
    for line in text.splitlines():
        data = line.split("#", 1)[0].strip()
        if not data:
            continue
        span, category = (field.strip() for field in data.split(";"))
        if category in categories:
            first, _, last = span.partition("..")
            rows.append((int(first, 16), int(last or first, 16)))
    merged: list[tuple[int, int]] = []
    for first, last in sorted(rows):
        if merged and merged[-1][1] + 1 == first:
            merged[-1] = (merged[-1][0], last)
        else:
            merged.append((first, last))
    return merged


def _escape(cp: int) -> str:
    return f"\\U{cp:08x}" if cp > 0xFFFF else f"\\u{cp:04x}"


def _class(ranges: list[tuple[int, int]]) -> str:
    return "".join(
        _escape(first) if first == last else f"{_escape(first)}-{_escape(last)}"
        for first, last in ranges
    )


def render(source: Path | None) -> str:
    text = _read(source)
    lines = [
        (
            f'"""Unicode {VERSION} letter, mark and number classes for ``pyfect.case``,\n'
            "generated by scripts/gen_case_unicode.py; do not edit. Each is the inside of a\n"
            'regex character class, in ``re`` escapes."""'
        ),
        "",
        f'VERSION = "{VERSION}"',
    ]
    for name, categories in CLASSES.items():
        body = _class(_ranges(text, categories))
        # A chunk must not end inside an escape: split only before a backslash.
        chunks: list[str] = []
        rest = body
        while rest:
            if len(rest) <= 84:
                chunks.append(rest)
                break
            cut = rest.rfind("\\", 0, 85)
            chunks.append(rest[:cut])
            rest = rest[cut:]
        lines.append(f"{name} = (")
        lines.extend(f'    r"{chunk}"' for chunk in chunks)
        lines.append(")")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, help="a directory with DerivedGeneralCategory.txt")
    parser.add_argument("--check", action="store_true", help="fail when the module is stale")
    args = parser.parse_args()
    text = render(args.source)
    if args.check:
        if OUT.read_text() != text:
            print(f"{OUT} is stale; run scripts/gen_case_unicode.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
