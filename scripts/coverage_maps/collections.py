def _rows(key: str, table: dict[str, str]) -> dict[str, tuple[str, str]]:
    return {name: (key, said) for name, said in table.items()}


def _compare(*names: str) -> dict[str, str]:
    """The ``Order``-derived exports of a module, said with operators."""
    said = {
        "Order": "`<` / `sorted`",
        "Equivalence": "`==`",
        "equals": "`==`",
        "isLessThan": "`<`",
        "isLessThanOrEqualTo": "`<=`",
        "isGreaterThan": "`>`",
        "isGreaterThanOrEqualTo": "`>=`",
        "between": "`low <= x <= high`",
        "clamp": "`min(max(x, low), high)`",
        "min": "`min`",
        "max": "`max`",
        "ReducerSum": "`sum`",
        "ReducerMultiply": "`math.prod`",
        "ReducerMax": "`max`",
        "ReducerMin": "`min`",
        "CombinerMax": "`max`",
        "CombinerMin": "`min`",
        "ReducerAnd": "`all`",
        "ReducerOr": "`any`",
        "ReducerConcat": "`''.join`",
    }
    return {name: said[name] for name in names}


