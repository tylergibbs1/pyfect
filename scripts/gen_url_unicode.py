"""Generate ``src/pyfect/_whatwg_url/_unicode_data.py``, the Unicode data the
URL host parser's IDNA step (UTS #46) reads: the IDNA mapping table, what
NFC needs (combining classes, canonical decompositions, composition
exclusions) and the bidi classes, joining types and marks its validity
checks need.

Node's URL (ada 4) uses Unicode 17.0.0; so do these tables, so a host maps
the same whatever Unicode version the running Python's ``unicodedata`` has.

    uv run python scripts/gen_url_unicode.py [--source DIR] [--check]

``--source`` reads the Unicode files from ``DIR`` instead of unicode.org;
``--check`` fails when the module on disk differs from what would be written.
"""

from __future__ import annotations

import argparse
import sys
import urllib.request
from collections.abc import Iterator
from pathlib import Path

VERSION = "17.0.0"
OUT = Path(__file__).resolve().parent.parent / "src" / "pyfect" / "_whatwg_url" / "_unicode_data.py"
FILES = {
    "IdnaMappingTable.txt": f"https://www.unicode.org/Public/{VERSION}/idna/IdnaMappingTable.txt",
    "DerivedBidiClass.txt": f"https://www.unicode.org/Public/{VERSION}/ucd/extracted/DerivedBidiClass.txt",
    "DerivedJoiningType.txt": f"https://www.unicode.org/Public/{VERSION}/ucd/extracted/DerivedJoiningType.txt",
    "DerivedCombiningClass.txt": f"https://www.unicode.org/Public/{VERSION}/ucd/extracted/DerivedCombiningClass.txt",
    "DerivedGeneralCategory.txt": f"https://www.unicode.org/Public/{VERSION}/ucd/extracted/DerivedGeneralCategory.txt",
    "UnicodeData.txt": f"https://www.unicode.org/Public/{VERSION}/ucd/UnicodeData.txt",
    "DerivedNormalizationProps.txt": f"https://www.unicode.org/Public/{VERSION}/ucd/DerivedNormalizationProps.txt",
}


def _read(source: Path | None, name: str) -> str:
    if source is not None:
        return (source / name).read_text()
    with urllib.request.urlopen(FILES[name]) as response:
        return response.read().decode()


def _rows(text: str) -> Iterator[tuple[int, int, list[str]]]:
    """``(first, last, fields)`` of each data line."""
    for line in text.splitlines():
        data = line.split("#", 1)[0].strip()
        if not data:
            continue
        fields = [field.strip() for field in data.split(";")]
        first, _, last = fields[0].partition("..")
        yield int(first, 16), int(last or first, 16), fields[1:]


def _merge(rows: Iterator[tuple[int, int, str]]) -> list[tuple[int, int, str]]:
    """Adjacent ranges with the same value as one range."""
    out: list[tuple[int, int, str]] = []
    for first, last, value in sorted(rows):
        if out and out[-1][2] == value and out[-1][1] + 1 == first:
            out[-1] = (out[-1][0], last, value)
        else:
            out.append((first, last, value))
    return out


def _idna(text: str) -> list[tuple[int, int, str]]:
    """Each range as ``V`` (valid; deviations are valid in nontransitional
    processing), ``X`` (disallowed), ``I`` (ignored) or ``M`` and the
    mapping's code points in hex."""
    kinds = {"valid": "V", "deviation": "V", "disallowed": "X", "ignored": "I"}

    def rows() -> Iterator[tuple[int, int, str]]:
        for first, last, fields in _rows(text):
            if fields[0] == "mapped":
                yield first, last, "M " + fields[1]
            else:
                yield first, last, kinds[fields[0]]

    return _merge(rows())


def _property(text: str, keep: frozenset[str]) -> list[tuple[int, int, str]]:
    return _merge((first, last, f[0]) for first, last, f in _rows(text) if f[0] in keep)


def _decompositions(text: str) -> list[tuple[int, int, str]]:
    """Each canonical decomposition (compatibility ones are tagged ``<...>``)."""
    out: list[tuple[int, int, str]] = []
    for line in text.splitlines():
        fields = line.split(";")
        if fields[5] and not fields[5].startswith("<"):
            cp = int(fields[0], 16)
            out.append((cp, cp, fields[5]))
    return out


def _block(name: str, ranges: list[tuple[int, int, str]]) -> str:
    lines = (
        f"{first:X} {value}" if first == last else f"{first:X}..{last:X} {value}"
        for first, last, value in ranges
    )
    return f'{name} = """\\\n' + "\n".join(lines) + '\n"""\n'


def render(source: Path | None) -> str:
    bidi = {"L", "R", "AL", "AN", "EN", "ES", "CS", "ET", "ON", "BN", "NSM"}
    marks = {"Mn", "Mc", "Me"}
    return (
        f'"""Unicode {VERSION} data for UTS #46, generated by scripts/gen_url_unicode.py;\n'
        'do not edit. Each line is ``FIRST[..LAST] VALUE`` in hex."""\n\n'
        f'VERSION = "{VERSION}"\n\n'
        + _block("IDNA", _idna(_read(source, "IdnaMappingTable.txt")))
        + "\n"
        + _block("BIDI", _property(_read(source, "DerivedBidiClass.txt"), frozenset(bidi)))
        + "\n"
        + _block(
            "JOINING",
            _property(_read(source, "DerivedJoiningType.txt"), frozenset({"D", "L", "R", "T"})),
        )
        + "\n"
        + _block(
            "COMBINING_CLASS",
            _merge(
                (first, last, f[0])
                for first, last, f in _rows(_read(source, "DerivedCombiningClass.txt"))
                if f[0] != "0"
            ),
        )
        + "\n"
        + _block("DECOMPOSITION", _decompositions(_read(source, "UnicodeData.txt")))
        + "\n"
        + _block(
            "COMPOSITION_EXCLUSION",
            _merge(
                (first, last, "X")
                for first, last, f in _rows(_read(source, "DerivedNormalizationProps.txt"))
                if f[0] == "Full_Composition_Exclusion"
            ),
        )
        + "\n"
        + _block(
            "MARK",
            _merge(
                (first, last, "M")
                for first, last, f in _rows(_read(source, "DerivedGeneralCategory.txt"))
                if f[0] in marks
            ),
        )
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, help="a directory with the Unicode files")
    parser.add_argument("--check", action="store_true", help="fail when the module is stale")
    args = parser.parse_args()
    text = render(args.source)
    if args.check:
        if OUT.read_text() != text:
            print(f"{OUT} is stale; run scripts/gen_url_unicode.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
