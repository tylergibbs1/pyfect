"""Exp 4: single-signature (non-overloaded) subtraction inside multi-step pipe."""
from __future__ import annotations
from collections.abc import Callable, Generator
from typing import Any, Never, Self, TypeVar, Generic, overload, reveal_type

A = TypeVar("A", covariant=True)
E = TypeVar("E", covariant=True, default=Never)
R = TypeVar("R", covariant=True, default=Never)
ROut = TypeVar("ROut", contravariant=True)
RIn = TypeVar("RIn", covariant=True, default=Never)

class Layer(Generic[ROut, E, RIn]): ...

class Effect(Generic[A, E, R]):
    @overload
    def pipe[B](self, f1: Callable[[Self], B], /) -> B: ...
    @overload
    def pipe[B, C](self, f1: Callable[[Self], B], f2: Callable[[B], C], /) -> C: ...
    @overload
    def pipe[B, C, D](self, f1: Callable[[Self], B], f2: Callable[[B], C], f3: Callable[[C], D], /) -> D: ...
    @overload
    def pipe[B, C, D, F](self, f1: Callable[[Self], B], f2: Callable[[B], C], f3: Callable[[C], D], f4: Callable[[D], F], /) -> F: ...
    def pipe(self, *fs: Any) -> Any: ...

class _Catch[EC, B, E2, R2]:
    @overload
    def __call__[AA, RR = Never](self, eff: Effect[AA, EC, RR]) -> Effect[AA | B, E2, RR | R2]: ...
    @overload
    def __call__[AA, RR = Never, ER = Never](self, eff: Effect[AA, EC | ER, RR]) -> Effect[AA | B, ER | E2, RR | R2]: ...
    def __call__(self, eff: Any) -> Any: ...

class _Provide[RO, E2, RI]:
    @overload
    def __call__[AA, EE = Never](self, eff: Effect[AA, EE, RO]) -> Effect[AA, EE | E2, RI]: ...
    @overload
    def __call__[AA, EE = Never, RR = Never](self, eff: Effect[AA, EE, RO | RR]) -> Effect[AA, EE | E2, RR | RI]: ...
    def __call__(self, eff: Any) -> Any: ...

def catch_tag[EC, B, E2 = Never, R2 = Never](tag: type[EC], handler: Callable[[EC], Effect[B, E2, R2]]) -> _Catch[EC, B, E2, R2]: ...
def provide[RO, E2 = Never, RI = Never](layer: Layer[RO, E2, RI]) -> _Provide[RO, E2, RI]: ...
def map_[AA, B](f: Callable[[AA], B]) -> Callable[[Effect[AA, Any, Any]], Effect[B, Any, Any]]: ...
def retry[EE](times: int) -> Callable[[Effect[Any, EE, Any]], Effect[Any, EE, Any]]: ...
def succeed[T](v: T) -> Effect[T]: ...

class A1: ...
class B1: ...
class C1: ...
class NotFound(Exception): ...
class Timeout(Exception): ...
class Other(Exception): ...

def two() -> Effect[int, NotFound | Timeout | Other, A1 | B1 | C1]: ...
def one() -> Effect[int, NotFound, A1]: ...
lay_ab: Layer[A1 | B1, ValueError] = Layer()
lay_c: Layer[C1] = Layer()
lay_a: Layer[A1] = Layer()

reveal_type(one().pipe(catch_tag(NotFound, lambda e: succeed("x"))))     # E Never
reveal_type(two().pipe(catch_tag(NotFound, lambda e: succeed("x"))))     # Timeout|Other
reveal_type(two().pipe(catch_tag(NotFound, lambda e: succeed("x")), catch_tag(Timeout, lambda e: succeed(1.0))))
reveal_type(two().pipe(catch_tag(NotFound, lambda e: succeed("x")), catch_tag(Timeout, lambda e: succeed(1.0)), catch_tag(Other, lambda e: succeed(b"")), provide(lay_ab)))
reveal_type(two().pipe(provide(lay_ab), provide(lay_c)))
reveal_type(one().pipe(provide(lay_a)))
reveal_type(one().pipe(catch_tag(Timeout, lambda e: succeed("x"))))  # tag not in E

# chained single-step pipes
reveal_type(two().pipe(catch_tag(NotFound, lambda e: succeed("x"))).pipe(catch_tag(Timeout, lambda e: succeed(1.0))).pipe(catch_tag(Other, lambda e: succeed(b""))).pipe(provide(lay_ab)).pipe(provide(lay_c)))
